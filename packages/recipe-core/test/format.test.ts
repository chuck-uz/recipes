import { describe, expect, it } from 'vitest'
import { formatNumber, formatQuantity } from '../src/index.js'

describe('дроби и числа', () => {
  it.each([
    [1, '1'],
    [2, '2'],
    [12, '12'],
    [0.25, '¼'],
    [0.5, '½'],
    [0.75, '¾'],
    [1.5, '1½'],
    [2.25, '2¼'],
    [3.75, '3¾'],
    [1.2, '1,2'],
    [0.3, '0,3'],
    // formatNumber отвечает за дроби; десятичный вид у метрических единиц
    // включает formatQuantity — см. «1,5 кг» ниже
    [187.5, '187½'],
    [2.7, '2,7'],
  ])('%s → %s', (input, expected) => {
    expect(formatNumber(input)).toBe(expected)
  })
})

describe('единицы: полные слова', () => {
  it.each([
    // чайная ложка
    [1, 'tsp', '1 чайная ложка'],
    [2, 'tsp', '2 чайные ложки'],
    [4, 'tsp', '4 чайные ложки'],
    [5, 'tsp', '5 чайных ложек'],
    [11, 'tsp', '11 чайных ложек'],
    [21, 'tsp', '21 чайная ложка'],
    [22, 'tsp', '22 чайные ложки'],
    // дробь — родительный падеж единственного числа
    [0.5, 'tsp', '½ чайной ложки'],
    [0.25, 'tsp', '¼ чайной ложки'],
    [1.5, 'tbsp', '1½ столовой ложки'],
    [2.5, 'tbsp', '2½ столовой ложки'],
    // столовая ложка
    [1, 'tbsp', '1 столовая ложка'],
    [3, 'tbsp', '3 столовые ложки'],
    [6, 'tbsp', '6 столовых ложек'],
    // щепотка
    [1, 'pinch', '1 щепотка'],
    [2, 'pinch', '2 щепотки'],
    [5, 'pinch', '5 щепоток'],
    [0.5, 'pinch', '½ щепотки'],
    // без склонения
    [500, 'g', '500 г'],
    [1, 'g', '1 г'],
    [2, 'kg', '2 кг'],
    [1.5, 'kg', '1,5 кг'],
    [200, 'ml', '200 мл'],
    [2, 'l', '2 л'],
    // штуки
    [1, 'pcs', '1 шт.'],
    [2, 'pcs', '2 шт.'],
    [0.5, 'pcs', '½ шт.'],
  ])('%s %s → %s', (amount, unit, expected) => {
    expect(formatQuantity(amount, unit as never)).toBe(expected)
  })

  it('по вкусу — без количества', () => {
    expect(formatQuantity(undefined, 'to_taste')).toBe('по вкусу')
  })
})

describe('единицы: сокращения', () => {
  it.each([
    [1, 'tsp', '1 ч. л.'],
    [0.5, 'tsp', '½ ч. л.'],
    [2, 'tbsp', '2 ст. л.'],
    [500, 'g', '500 г'],
    [2, 'pcs', '2 шт.'],
    // у щепотки сокращения нет — остаётся полное слово
    [2, 'pinch', '2 щепотки'],
  ])('%s %s → %s', (amount, unit, expected) => {
    expect(formatQuantity(amount, unit as never, { abbreviated: true })).toBe(expected)
  })
})
